/** Есть ли в строке похожее на сказуемое слово (с поправкой на ложных друзей). */
export function hasVerbHint(text: string): boolean {
  const words = text.toLowerCase().match(/[а-яё]+/g) ?? [];
  return words.some((word) => !VERB_LOOKALIKES.has(word) && VERB_HINT_RE.test(word));
}

