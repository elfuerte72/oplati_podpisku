/**
 * Паттерны правил Threads. Отдельно от правил канала: у площадки другой жанр,
 * а не другая строгость — разметки нет вовсе, ссылка живёт в последнем ответе,
 * реакции не выпрашиваются (Meta понижает такое официально).
 */

/** Решётка в тексте. Тему задаёт параметр `tag`, а не текст. */
export const THREADS_HASH_RE = /(?<!\S)#[^\s#]+/g;

/**
 * Разметка, которую Threads покажет буквально: звёздочки и подчёркивания,
 * решётки заголовков, обратные апострофы, ссылки в скобках, таблицы, цитаты,
 * HTML, «математический жирный» из Unicode (скринридер читает его по буквам),
 * маркеры-буллеты. Дефис-список и нумерация строками — обычный текст, он
 * разрешён.
 */
export const THREADS_MARKUP_RE = new RegExp(
  '\\*\\*|\\*[^\\s*][^*\\n]*\\*|__|`|^\\s{0,3}#{1,6}\\s|^\\s{0,3}>\\s|^\\s*\\|.*\\|\\s*$' +
    '|\\[[^\\]]+\\]\\([^)]*\\)|</?[a-z]+[^>]*>|[\\u{1D400}-\\u{1D7FF}]|^\\s*[•▪◾◼►▸‣]',
  'imu',
);

/** Нумерация цепочки: «1/14» читатель закрывает, а Threads и сам её показывает. */
export const THREADS_NUMBERING_RE =
  /(?:^|\s)\d{1,2}\s*\/\s*\d{1,2}(?=\s|$|[.,:])|(?<![а-яё])часть\s+\d/i;

/**
 * Engagement bait. Meta понижает такое официально (Recommendation Guidelines):
 * просьбы о реакциях, «напиши да», отметки друзей, розыгрыши. Настоящий вопрос
 * по теме — не bait.
 */
export const THREADS_BAIT_RE =
  /лайк,? если|ставь(?:те)? лайк|напиши(?:те)? (?:да|\+|плюс)|согласн[ыа]\?|отметь(?:те)? друг|розыгрыш|кто со мной\?|пиши(?:те)? в комментах|репостни|сделай(?:те)? репост|жми(?:те)? (?:лайк|сердечк)/i;

/**
 * Реклама по 72-ФЗ (с 01.09.2025 на ресурсах Meta запрещена). Информировать о
 * своей услуге можно; промокоды, скидки, «только сегодня» и превосходные
 * степени ФАС считает рекламой.
 */
export const THREADS_AD_RE =
  /промокод|скидк[аиуео]|(?<![а-яё])акци[яию](?![а-яё])|только (?:сегодня|до|сейчас)|успей|выгоднее всех|лучший сервис|самый выгодный|дешевле всех/i;

/** Тема не может содержать точку, амперсанд и переносы. */
export const THREADS_TAG_BAD_RE = /[.&\n\t]/;

/**
 * Ссылка в тексте. Считается по частям: в первом посте её быть не должно.
 *
 * Левая граница задана lookbehind, а не обязательным пробелом: ссылка в
 * скобках и после двоеточия — обычное дело, а правило «ссылка одна и в
 * последнем ответе» их не видело.
 */
export const URL_RE = /https?:\/\/[^\s)»"']+|(?<![\w@.])(?:t\.me|www\.)[^\s)»"']+/gi;
