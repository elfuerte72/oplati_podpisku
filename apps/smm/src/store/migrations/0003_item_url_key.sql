-- Дедуп элементов по НОРМАЛИЗОВАННОМУ адресу (ревью тикета 10).
--
-- `url` остаётся тем, что можно открыть; ключом сравнения становится адрес
-- без хвостов трекинга, `www` и завершающего слеша: один материал приходит из
-- канала, RSS и HN с разными `utm_source`, и по сырому адресу это были три
-- разные строки — три идеи в дайджесте и три платных оценки об одном событии.
ALTER TABLE items ADD COLUMN url_key TEXT;

-- Существующие строки: ключ равен адресу, пока их не встретят снова. Пересчёт
-- в SQL невозможен (нормализация живёт в коде), а терять их незачем.
UPDATE items SET url_key = url WHERE url_key IS NULL;

CREATE UNIQUE INDEX items_url_key_idx ON items (url_key);
