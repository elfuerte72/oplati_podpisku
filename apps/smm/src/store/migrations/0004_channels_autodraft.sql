-- Куда вышел пост: ключ канала из конфига (`main` | `second`), NULL до
-- публикации. Пост — это ОДНА публикация в ОДНОМ канале: «в оба» создаёт
-- копию для второго канала, и у каждой строки свои просмотры и своё «снят с
-- витрины». Отдельная таблица публикаций потребовала бы переписать машину
-- статусов; копия переиспользует её целиком.
ALTER TABLE posts ADD COLUMN channel TEXT;
UPDATE posts SET channel = 'main' WHERE platform = 'telegram' AND channel_message_id IS NOT NULL;

-- Номера сообщений в разных каналах совпадают: уникальна ПАРА, а не номер.
-- Прежний индекс на одном номере бросал бы уже ПОСЛЕ отправки во второй канал,
-- и пост уходил бы в канал, не записавшись опубликованным.
-- ⚠️ Ключ — `COALESCE(channel, 'main')`, а не голый `channel`: NULL в уникальном
-- индексе SQLite всегда «разный», и номер без канала перестал бы охраняться.
-- Номер без канала — это основной канал (так жили все посты до этой миграции).
DROP INDEX posts_message_idx;
CREATE UNIQUE INDEX posts_channel_message_idx
  ON posts (COALESCE(channel, 'main'), channel_message_id)
  WHERE channel_message_id IS NOT NULL;

-- Откуда пост: начат владельцем или пришёл черновиком по расписанию. По нему
-- считается, сколько автодрафтов ждут решения (потолок неразобранных).
ALTER TABLE posts ADD COLUMN origin TEXT NOT NULL DEFAULT 'owner'
  CHECK (origin IN ('owner', 'auto'));
CREATE INDEX posts_origin_idx ON posts (origin, platform, status);

-- Варианты угла из плана (JSON). Автодрафт живёт вне диалога владельца, а
-- «Другой угол» нужен и ему: без колонки варианты жили только в `flow`.
ALTER TABLE posts ADD COLUMN angles TEXT;

