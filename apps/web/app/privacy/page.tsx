/** Срок хранения словами: 730 → «2 года», 400 → «400 дней». */
function retentionText(days: number): string {
  if (days % 365 === 0) {
    const years = days / 365;
    const word = years === 1 ? 'год' : years < 5 ? 'года' : 'лет';
    return `${years} ${word}`;
  }
  return `${days} дней`;
}

