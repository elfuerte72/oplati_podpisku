/**
 * Человекочитаемый текст по коду ошибки кабинета.
 *
 * Живёт отдельным модулем, потому что нужен ДВУМ сторонам (ревью 2026-08-11):
 * `CabinetClient` рисует им экраны загрузки, а `cabinet-api` подставляет его
 * туда, где сервер прислал только код. Схемы действий (`payResultSchema`,
 * `orderCreationResultSchema`) требуют в ветке `ok:false` поле `message`, а
 * ответы 401/429/503 роута его не несут — без общей карты клиент показывал бы
 * на них «Сеть недоступна. Попробуй ещё раз.», то есть звал бы долбить кнопку
 * там, где надо переоткрыть кабинет или переждать.
 */
export function errorTextFor(error: string): string {
  switch (error) {
    case 'expired':
      return 'Сессия устарела. Закрой кабинет и открой заново из бота.';
    case 'bad_signature':
    case 'missing_hash':
    case 'missing_user':
    case 'malformed':
      return 'Не удалось подтвердить вход из Telegram. Открой кабинет заново из бота.';
    case 'misconfigured':
      return 'Кабинет временно не настроен. Загляни немного позже.';
    case 'rate_limited':
      return 'Слишком много запросов подряд. Подожди минутку и попробуй снова.';
    case 'db_unavailable':
      return 'База временно недоступна. Загляни через пару минут.';
    default:
      return 'Не удалось загрузить данные. Попробуй обновить страницу.';
  }
}
