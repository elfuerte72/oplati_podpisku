import { describe, expect, it } from 'vitest';

import { SECTION_TITLES } from '@/lib/panel/labels';

import { PANEL_ICON_NAMES, SECTION_ICON_NAMES } from './PanelIcon';

/**
 * Полнота набора значков.
 *
 * Полноту держит тип (`Record<SectionKey, ReactElement>`), и пока он на
 * месте, этот тест доказывает то же самое второй раз. Его ценность — в
 * ОБРАТНОМ направлении: тип не заметит, если `SectionKey` подменят на
 * `string` или в набор попадёт ключ без раздела, а значок — единственное имя
 * раздела в свёрнутом меню: раздел без него становится там пустой полосой,
 * на которую человек не нажмёт.
 */
describe('набор значков панели', () => {
  it('набор значков разделов совпадает со словарём разделов один в один', () => {
    // Равенство МНОЖЕСТВ, а не «каждый раздел есть в наборе»: значок с ключом,
    // которого в словаре нет, — след переименования (раздел переехал, а
    // значок остался под старым именем и рисоваться уже не будет ни у кого).
    expect(new Set(SECTION_ICON_NAMES)).toEqual(new Set(Object.keys(SECTION_TITLES)));
  });

  it('значки оболочки на месте: меню, поиск, тумблеры вида, выход', () => {
    // Эти нажимаются без подписи рядом, и пропажа любого оставила бы пустую
    // кнопку — визуально исправную и бессмысленную.
    for (const name of ['menu', 'search', 'collapse', 'expand', 'chevronDown', 'logout', 'sun', 'moon']) {
      expect(PANEL_ICON_NAMES).toContain(name);
    }
  });
});
