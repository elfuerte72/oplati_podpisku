/**
 * Значок. Всегда `aria-hidden`: рядом обязан стоять текст — либо видимый, либо
 * `panel-visually-hidden`. Иконка, оставшаяся единственным именем кнопки,
 * читается голосом экрана как «кнопка».
 */
export function PanelIcon({ name, className }: { name: PanelIconName; className?: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      // Размер от текста: одна иконка на все плотности и на свёрнутое меню.
      width="1em"
      height="1em"
      className={className ? `panel-icon ${className}` : 'panel-icon'}
      aria-hidden
      focusable="false"
    >
      {ICONS[name]}
    </svg>
  );
}

