import { NOTE_KIND_CLASS, type PanelNoteKind } from '@/lib/panel/class-names';

/**
 * Строка отклика формы: успех, предупреждение, отказ.
 *
 * Один элемент на все формы панели (вариант A дизайн-аудита, тикет 05). До
 * него об успехе сообщали четырьмя разными способами, а предупреждение
 * «клиенту отправлено, но в переписку не записалось» красилось КАК ОТКАЗ — и
 * провоцировало ровно неверное действие: повторить отправку, то есть прислать
 * клиенту второе сообщение.
 *
 * ⚠️ `role="status"` с `aria-live="polite"` — не украшение: тихая строка,
 * которую программа чтения с экрана не объявляет, для незрячего сотрудника
 * равна молчанию, а молчание здесь и было исходной бедой.
 */
export function PanelNote({
  kind,
  children,
}: {
  /** `ok` — получилось; `warn` — получилось, но есть оговорка; `error` — не получилось. */
  kind: PanelNoteKind;
  children?: React.ReactNode;
}) {
  return (
    <p className={NOTE_KIND_CLASS[kind]} role="status" aria-live="polite">
      {children}
    </p>
  );
}
