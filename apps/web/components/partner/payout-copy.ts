/**
 * Тексты про выплату партнёру — ОДИН источник на все экраны.
 *
 * Формулировка жила двумя независимыми строками (модалка вывода и сообщение о
 * принятой заявке), и правка одной оставляла вторую врать.
 *
 * Содержание — следствие того, как выплаты устроены на самом деле: автоматики
 * нет, платит менеджер (решение владельца 2026-08-14), а весь кабинет считается
 * в долларах, тогда как деньги партнёр получает в рублях. Курс нигде не
 * фиксируется технически — и это нормально для ручной выплаты, но правило
 * обязано быть сказано ДО подачи заявки: иначе первый же вопрос «почему столько»
 * разбирается постфактум в переписке, когда партнёр уже увидел сумму в $.
 */

/** Как проходит выплата — показывается рядом с балансом до подачи заявки. */
export const PAYOUT_MANUAL_NOTE =
  'Баланс считается в долларах. Выплату проводим вручную: после заявки напишем ' +
  'в Telegram, уточним реквизиты и переведём в рублях по курсу на день выплаты — ' +
  'обычно в течение 3 рабочих дней.';

/**
 * Подтверждение принятой заявки. Сумма приходит уже отформатированной ($12.34),
 * чтобы формат денег остался в `format-usd`.
 */
export function payoutAcceptedMessage(formattedAmount: string): string {
  return (
    `Заявка на вывод ${formattedAmount} принята. Напишем в Telegram, уточним ` +
    'реквизиты и переведём в рублях по курсу на день выплаты — обычно в течение ' +
    '3 рабочих дней.'
  );
}
