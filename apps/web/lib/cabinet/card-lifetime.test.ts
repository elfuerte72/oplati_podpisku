import { describe, expect, it } from 'vitest';

import { cardValidUntil } from './read';
import { CARD_LIFETIME_DAYS } from './types';

/**
 * «Действует до» — раньшая из двух дат: срок платёжной сети (`exp_date`) и наш
 * `CARD_LIFETIME_DAYS`. До 2026-07-30 приоритет был безусловно за `exp_date`,
 * из-за чего кабинет обещал срок на годы больше реального.
 */
describe('cardValidUntil', () => {
  it('без live-данных: дата выпуска + 180 дней (пример из ТЗ: 12.07.2026 → 08.01.2027)', () => {
    expect(CARD_LIFETIME_DAYS).toBe(180);
    expect(cardValidUntil(new Date('2026-07-12T10:00:00.000Z'))).toBe('2027-01-08T10:00:00.000Z');
  });

  it('exp_date РАНЬШЕ нашего срока → показываем exp_date: сеть откажет первой', () => {
    // 20:59:59Z = 23:59:59 МСК — UI рендерит в Europe/Moscow, полночь UTC
    // показывалась бы как 1-е число следующего месяца.
    expect(cardValidUntil(new Date('2026-07-12T10:00:00.000Z'), '09/26')).toBe(
      '2026-09-30T20:59:59.000Z',
    );
  });

  it('exp_date ПОЗЖЕ нашего срока → показываем наш срок: карту закроет recycle-cards', () => {
    expect(cardValidUntil(new Date('2026-07-12T10:00:00.000Z'), '09/27')).toBe(
      '2027-01-08T10:00:00.000Z',
    );
  });

  /**
   * Тот самый случай, с которого начался разбор: карта ***7145, выпущена
   * 25.06.2026, `exp_date=06/30`. Кабинет показывал «30 июня 2030» (а без года —
   * просто «30 июня», что читалось как прошлый месяц), тогда как cron закрывает
   * карту 22.12.2026.
   */
  it('регресс: карта 25.06.2026 с exp_date 06/30 действует до 22.12.2026, а не до 2030', () => {
    expect(cardValidUntil(new Date('2026-06-25T05:09:00.000Z'), '06/30')).toBe(
      '2026-12-22T05:09:00.000Z',
    );
  });

  it('конец февраля високосного года берётся верно, когда сеть истекает первой', () => {
    expect(cardValidUntil(new Date('2027-12-01T10:00:00.000Z'), '02/28')).toBe(
      '2028-02-29T20:59:59.000Z',
    );
  });

  it('кривой exp_date → fallback на расчётные 180 дней', () => {
    expect(cardValidUntil(new Date('2026-07-12T10:00:00.000Z'), '13/27')).toBe(
      '2027-01-08T10:00:00.000Z',
    );
    expect(cardValidUntil(new Date('2026-07-12T10:00:00.000Z'), '2027-09-30')).toBe(
      '2027-01-08T10:00:00.000Z',
    );
  });
});
