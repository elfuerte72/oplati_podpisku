/**
 * «Оплачен, но выдача карты упала» — одно правило и одни слова для вкладки
 * «Карта», листа заказа Mini App и сообщения бота.
 *
 * `failed` у заказа означает разное: недоплату и отвергнутый счёт (денег нет) и
 * сбой выдачи после оплаты (деньги есть, карты нет). Различает их `paidAt`:
 * время оплаты ставит переход в `paid`, а недоплата до него не доходит. Второй
 * случай раньше выглядел для клиента как тишина: «Выпускаю карту…» сменялось
 * «Карты пока нет», а на листе — красная «Ошибка» без слов.
 *
 * Модуль без импортов: его читают и клиентский бандл кабинета, и бот
 * (`lib/telegram/templates.ts`).
 */

export type IssueFailedOrderLike = {
  status: string;
  /** Необязательное: снапшот сервера прошлого деплоя поля мог не нести. */
  paidAt?: string | null | undefined;
};

export function isPaidButIssueFailed(order: IssueFailedOrderLike): boolean {
  return order.status === 'failed' && typeof order.paidAt === 'string' && order.paidAt !== '';
}

/**
 * Сколько «выдача сорвалась» показывается клиенту. Сбой выдачи разбирают часами,
 * а не неделями; дольше экран врал бы тому, кому оператор уже вернул деньги вне
 * системы (`refunded` в проде не ставит никто, заказ так и остаётся `failed`).
 */
export const ISSUE_FAILED_MAX_AGE_MS = 3 * 24 * 60 * 60 * 1000;

/**
 * Сбой выдачи и он свежее `maxAgeMs`. Возраст — от ОПЛАТЫ, а не от создания
 * заказа: заказ с проверки банка (`payment_review` не протухает) оплачивается
 * и через несколько дней, и по `createdAt` его сбой не показался бы вовсе
 * (ревью 2026-09-25, ось E).
 */
export function isRecentIssueFailure(
  order: IssueFailedOrderLike,
  now: number,
  maxAgeMs: number = ISSUE_FAILED_MAX_AGE_MS,
): boolean {
  if (!isPaidButIssueFailed(order) || typeof order.paidAt !== 'string') return false;
  return now - Date.parse(order.paidAt) <= maxAgeMs;
}

/** Заголовок вкладки «Карта»: «Карта для ChatGPT задерживается». */
export function issueFailedTitle(service: string): string {
  return `Карта для ${service} задерживается`;
}

