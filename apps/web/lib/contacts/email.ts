import { z } from 'zod';

/**
 * Нормализация email клиента — ОБЩАЯ для клиента (плашка контактов) и сервера
 * (роуты confirm/cabinet): одна проверка на обеих сторонах, чтобы UI не
 * пропускал то, что сервер отвергнет, и наоборот. Поэтому файл без
 * `server-only`.
 *
 * Без кода подтверждения — формата достаточно (решение владельца, спека §3.2):
 * клиент сам заинтересован дать живой ящик, туда придёт письмо банка, если
 * платёж встанет на проверку.
 */

/**
 * Код ошибки «нужна почта» — ЕДИНСТВЕННЫЙ источник литерала: его пишет
 * продюсер контракта (`payments/create`), читают tool-handler `confirm_order`
 * и роуты. Разъезд строки здесь ломал бы классификацию ошибки молча.
 */
export const EMAIL_REQUIRED = 'email_required';

/** Текст отказа для клиентских каналов — один на веб и кабинет. */
export const EMAIL_REQUIRED_TEXT =
  'Укажи почту для связи по заказу — без неё счёт не выставляется.';

/** Текст невалидного адреса — общий для роутов и подсказки в плашке. */
export const EMAIL_INVALID_TEXT = 'Почта выглядит некорректно — проверь адрес.';

/** RFC-максимум длины адреса; больше — заведомо мусор. */
const emailSchema = z.string().trim().min(3).max(254).email();

/** Приводит ввод к каноническому виду (trim) или отдаёт null, если не email. */
export function normalizeEmail(raw: string): string | null {
  const parsed = emailSchema.safeParse(raw);
  return parsed.success ? parsed.data : null;
}
