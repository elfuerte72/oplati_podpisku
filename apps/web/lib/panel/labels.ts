/**
 * Доступное имя счётчика в меню. Число согласуется с глаголом по правилам
 * русского: «1 требует», «2 требуют», «21 требует», «11 требуют».
 */
export function attentionLabel(count: number): string {
  const n = Math.abs(Math.trunc(count));
  const singular = n % 10 === 1 && n % 100 !== 11;
  return `${count} ${singular ? 'требует' : 'требуют'} внимания`;
}

