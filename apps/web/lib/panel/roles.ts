import type { StaffRole } from '@oplati/db';

/**
 * Подписи ролей персонала — ЕДИНСТВЕННОЕ место, где роль превращается в текст.
 *
 * `Record<StaffRole, string>` обязывает перечислить ВСЕ значения enum'а: без
 * этого «всё, что не admin, — менеджер» тихо подписывало бы `supervisor`
 * (значение в enum осталось с прежней схемы) чужой ролью. Роль решает, что
 * человеку можно, и ошибка в её подписи вводит в заблуждение того, кто
 * раздаёт доступ.
 */
export const STAFF_ROLE_LABELS: Record<StaffRole, string> = {
  admin: 'владелец',
  operator: 'менеджер',
  // Роль не заводится (спека §2: «Ролей supervisor не делаем»), но значение
  // enum'а живо, и строка в базе с ним подписывается честно, а не «менеджером».
  supervisor: 'супервизор (роль не используется)',
};

export function staffRoleLabel(role: StaffRole): string {
  // `?? role` — не «на всякий случай», а страховка от строки в БД с ролью,
  // которой в типе уже нет: печатаем как есть, а не подписываем чужой.
  return STAFF_ROLE_LABELS[role] ?? role;
}
