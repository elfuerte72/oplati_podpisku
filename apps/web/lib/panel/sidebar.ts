/**
 * Состояние бокового меню панели: развёрнуто или свёрнуто до иконок.
 *
 * ⚠️ Состояние живёт в COOKIE, а не в памяти компонента. Причина не в
 * долговечности: `PanelShell` рендерит КАЖДАЯ страница (в `layout.tsx` его нет
 * — там же живёт экран входа, где актора ещё не существует), поэтому при любом
 * переходе оболочка монтируется заново и React-состояние теряется. Свёрнутое
 * меню разворачивалось бы на каждом клике.
 *
 * ⚠️ Читает cookie СЕРВЕР и отдаёт готовую разметку. Если читать её в браузере
 * после гидратации, первый кадр приходит развёрнутым и меню прыгает.
 *
 * Это настройка вида, а не секрет: cookie доступна скрипту (её же пишет
 * кнопка) и не участвует ни в одной проверке доступа.
 */

/** Имя cookie. Общее для читателя (сервер) и писателя (кнопка). */
export const SIDEBAR_COOKIE = 'panel_sidebar';

/** Значение свёрнутого состояния. Развёрнутое — отсутствие cookie. */
export const SIDEBAR_COLLAPSED_VALUE = 'collapsed';

/** Год: настройка вида, переспрашивать её каждую сессию незачем. */
export const SIDEBAR_COOKIE_MAX_AGE_SECONDS = 60 * 60 * 24 * 365;

/**
 * Свёрнуто ли меню по значению cookie.
 *
 * Развёрнутое состояние — умолчание: незнакомое значение (старая версия,
 * ручная правка) трактуется как «развёрнуто», потому что развёрнутое меню
 * читается без обучения, а свёрнутое — набор иконок.
 */
export function isSidebarCollapsed(cookieValue: string | undefined): boolean {
  return cookieValue === SIDEBAR_COLLAPSED_VALUE;
}

/**
 * Строка `document.cookie` для записи состояния из браузера.
 *
 * Собирается здесь, а не в компоненте, чтобы имя, срок и путь были описаны
 * один раз: cookie с другим `Path` не перезаписывает прежнюю, а ложится
 * второй — и меню начинает зависеть от того, с какого экрана его свернули.
 */
export function sidebarCookieString(collapsed: boolean): string {
  const value = collapsed ? SIDEBAR_COLLAPSED_VALUE : '';
  const maxAge = collapsed ? SIDEBAR_COOKIE_MAX_AGE_SECONDS : 0;
  // `Secure` — для единообразия с cookie сессии: панель живёт только по HTTPS
  // (localhost браузеры считают защищённым, поэтому разработка не страдает).
  // На доступ эта cookie не влияет ни в одной проверке, но и исключением из
  // общего правила быть не должна.
  return `${SIDEBAR_COOKIE}=${value}; Path=/; Max-Age=${maxAge}; SameSite=Lax; Secure`;
}
