import { effectiveMode } from '@/lib/support/session';

/**
 * Режим разговора, который показывает панель, — ЭФФЕКТИВНЫЙ, а не записанный в
 * БД (crm-serious-fixes, тикет 03, SUP-13).
 *
 * Сессия помощника гаснет лениво: срок замечает следующее сообщение клиента, и
 * до него в БД остаётся `ai`. Экран, рисующий сырой режим, бессрочно говорил
 * «Помощник» там, где клиентом не занимается никто, — а оператор читал это как
 * «разговор ведёт помощник, мне туда не надо».
 *
 * Правило истечения — `effectiveMode` модуля поддержки, а не своя копия: копия
 * разошлась бы с тем, как бот на самом деле обработает следующее сообщение.
 *
 * ⚠️ Только для серверных страниц: модуль поддержки в клиентский бандл не
 * тянется. Клиентские компоненты панели берут правила из `lib/panel/support.ts`.
 */
export function effectiveSupportMode(
  handoffMode: string,
  modeExpiresAt: Date | null,
  now: Date = new Date(),
): string {
  // Лениво гаснет только сессия помощника. Разговор у оператора закрывает крон
  // автозакрытия, и показывать его закрытым раньше крона значило бы соврать.
  if (handoffMode !== 'ai') return handoffMode;
  return effectiveMode({ mode: 'ai', modeExpiresAt, assignedOperatorId: null }, now).mode;
}
