import 'server-only';

import { isCardTopupSafe } from '@oplati/types';

import { serverEnv } from '../env.server.ts';
import { cardFundingUsdCents } from './format.ts';

/**
 * Пригодна ли живая карта клиента для долива — ОДНО правило на весь проект.
 *
 * Правило решает две разные вещи, и обе обязаны отвечать одинаково: выпускать
 * ли карту в `issue-card` и брать ли комиссию за выпуск в требовании фонда
 * (ниже). Разъедься они — гейт посчитает заказ дешевле, чем он окажется у
 * провайдера, и пропустит ровно тот случай, ради которого заведён.
 *
 * `null` (карты нет) — тоже ответ: выпуск новой. Карта в последние сутки жизни
 * доливу не подлежит (аудит 2026-08-10, HIGH): её закроет ночной
 * `recycle-cards` необратимым `release`, и деньги клиента вернутся на наш VCC.
 */
export function isCardReusable(card: { createdAt: Date } | null, now: Date = new Date()): boolean {
  return card !== null && isCardTopupSafe(card.createdAt, now);
}

/**
 * Сколько долларов снимется с карточного фонда PaySpace ради ОДНОГО заказа.
 *
 * Единственный ответ на этот вопрос в проекте. До тикета 01 трека vcc-preflight
 * формула была написана дважды — в сумме фондирования карты (`format.ts`) и в
 * пороге алёрта низкого баланса (`jobs/vcc-balance.ts`), — то есть была
 * зеркалом без автосверки (инвариант 10 CLAUDE.md). Разъезд стоил бы дорого:
 * порог алёрта и решение «выставлять ли счёт» обязаны считать одно и то же
 * число, иначе гейт пропускает заказ, про который алёрт уже кричит (или
 * наоборот).
 *
 * Состав требования:
 *   - сумма НА карту = цена сервиса + буфер (VAT/FX/foreign-fee), см.
 *     `cardFundingUsdCents`;
 *   - комиссия провайдера за ВЫПУСК новой карты — только когда карту придётся
 *     выпускать. Долив живой карты провайдеру ничего не стоит.
 *
 * ⚠️ `issue-card` эту функцию НЕ зовёт, и это не упущение: он считает сумму,
 * которая ложится НА карту (`cardFundingUsdCents`), а комиссию за выпуск
 * провайдер берёт с фонда сверх неё. Общий у них знаменатель — та самая
 * `cardFundingUsdCents`, и правило «нужна ли новая карта» — `isCardReusable`
 * выше. Двух формул больше нет ни там, ни тут.
 *
 * ⚠️ `CARD_ISSUE_FEE_USD_CENTS` сегодня служит двум господам: это и надбавка
 * КЛИЕНТУ в цене (`propose-order`, снимок в `orders.card_issue_fee_kopecks`), и
 * фактический сбор ПРОВАЙДЕРА за выпуск, который списывается с нашего
 * VCC-баланса. Пока оба значения совпадают ($4), одной переменной достаточно;
 * если они разойдутся, здесь понадобится вторая — цена клиенту и расход фонда
 * перестанут быть одним числом. Чинить это заранее не нужно (спека §4.1).
 */
export function orderFundingRequirementUsdCents(input: {
  /** Цена сервиса в USD-центах — `orders.original_amount`. */
  priceUsdCents: number;
  /**
   * Карту придётся выпускать новую: живой карты, пригодной для долива, у
   * клиента нет (`findActiveByUserId` + `isCardTopupSafe` — та же пара, что
   * решает это в `issue-card`).
   */
  needsNewCard: boolean;
}): number {
  const funding = cardFundingUsdCents(input.priceUsdCents, serverEnv.PAYSPACE_CARD_BUFFER_PERCENT);
  return funding + (input.needsNewCard ? serverEnv.CARD_ISSUE_FEE_USD_CENTS : 0);
}
