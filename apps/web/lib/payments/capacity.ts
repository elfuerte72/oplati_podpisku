/**
 * Отказ «карту сейчас выпустить нечем» — маркер и текст клиенту.
 *
 * Живёт отдельно от `confirm-order.ts` намеренно: текст нужен и `payments/create`
 * (в теле 422), и трём клиентским каналам, а `confirm-order` тянет за собой
 * server-only-зависимости, которых в клиентских компонентах быть не должно.
 *
 * ⚠️ Почему 422, а не 503. `provider_unavailable` в проекте значит «транспорт
 * платёжного шлюза лёг, попробуй позже». Здесь другое: шлюз жив, счёт выставить
 * технически можно, но мы не должны. Семантически это сосед `email_required` и
 * `phone_required` — запрос корректен, условие не выполнено.
 */
export const FULFILLMENT_CAPACITY = 'fulfillment_capacity';

/**
 * Через сколько звать клиента вернуться.
 *
 * Зеркала здесь больше нет: инструкция AI-агенту (`PaymentCapacityError`) не
 * пересказывает этот срок своими словами, а передаёт готовый текст отсюда —
 * иначе бот и сайт звали бы человека в разное время, и разъезд заметил бы
 * только он сам.
 */
const CAPACITY_RETRY_WINDOW = '10-15 минут';

/**
 * Сколько минут фиксации цены должно остаться, чтобы звать клиента вернуться
 * самому.
 *
 * Меньше — и совет «попробуйте через 10-15 минут» приводит его к протухшей
 * цене и предложению оформить заказ заново. В таком случае честнее сразу
 * отправить в поддержку: там успеют оформить вручную.
 */
const PRICE_LOCK_TIGHT_MINUTES = 20;

/**
 * Текст клиенту. Единственное, что он видит по этому сценарию.
 *
 * Собран по практике сообщений о недоступности сервиса (NN/g «Error-Message
 * Guidelines», исследования чекаута Baymard): сказать понятным языком, ЧТО
 * происходит, подтвердить, что с его данными всё в порядке, дать конкретный
 * следующий шаг и запасной путь. Ни жаргона, ни кодов, ни обвинений — клиент
 * ничего не сделал не так.
 *
 * ⚠️ Про срок фиксации цены в тексте НЕТ ни слова, хотя раньше был (решение
 * владельца 2026-08-25, отменяет В3). Клиент не выбирал этот таймер и до
 * отказа о нём не слышал: упомянуть его — значит вместо ответа «что делать»
 * выдать новую тревогу, что у него что-то истекает. Ровно так исследования
 * чекаута описывают обратный эффект урочности — давление там, где человек и
 * так расстроен. Срок по-прежнему решает, КАКОЙ дать совет, но наружу не
 * выходит.
 *
 * Про баланс, фонд и PaySpace — тем более молчим: устройство нашей казны не
 * его забота, а «недостаточно средств» он прочитал бы как проблему СВОЕЙ карты.
 *
 * ⚠️ Обращение на «ВЫ» — решение владельца, и оно расходится с остальным
 * продуктом: чат, бот и кабинет говорят на «ты». Будут выравнивать голос —
 * правьте вместе, иначе один экран выпадает.
 */
export function fulfillmentCapacityText(priceLockMinutesLeft: number | null): string {
  const intro = 'Оплата сейчас не проходит — небольшая заминка, уже разбираюсь.';

  // Времени в обрез: возвращаться самому уже поздно, но клиенту незачем знать
  // почему — ему нужен работающий шаг, а не наша арифметика.
  if (priceLockMinutesLeft !== null && priceLockMinutesLeft < PRICE_LOCK_TIGHT_MINUTES) {
    return (
      `${intro} Заказ сохранён — напишите в поддержку, ` +
      'оформим вручную: так будет быстрее всего.'
    );
  }

  return (
    `${intro} Заказ сохранён: попробуйте оплатить через ${CAPACITY_RETRY_WINDOW}. ` +
    'Если не выйдет — напишите в поддержку, оформим вручную.'
  );
}
