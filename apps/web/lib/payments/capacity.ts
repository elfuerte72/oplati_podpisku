/**
 * Отказ «карту сейчас выпустить нечем» — маркер и текст клиенту.
 *
 * Живёт отдельно от `confirm-order.ts` намеренно: текст нужен и `payments/create`
 * (в теле 422), и трём клиентским каналам, а `confirm-order` тянет за собой
 * server-only-зависимости, которых в клиентских компонентах быть не должно.
 *
 * ⚠️ Почему 422, а не 503. `provider_unavailable` в проекте значит «транспорт
 * платёжного шлюза лёг, попробуй позже». Здесь другое: шлюз жив, счёт выставить
 * технически можно, но мы не должны. Семантически это сосед `email_required` и
 * `phone_required` — запрос корректен, условие не выполнено.
 */
export const FULFILLMENT_CAPACITY = 'fulfillment_capacity';

/**
 * Через сколько звать клиента вернуться.
 *
 * Зеркала здесь больше нет: инструкция AI-агенту (`PaymentCapacityError`) не
 * пересказывает этот срок своими словами, а передаёт готовый текст отсюда —
 * иначе бот и сайт звали бы человека в разное время, и разъезд заметил бы
 * только он сам.
 */
const CAPACITY_RETRY_WINDOW = '10-15 минут';

/**
 * Сколько минут фиксации цены должно остаться, чтобы звать клиента вернуться
 * самому.
 *
 * Меньше — и фраза начинает спорить сама с собой: «цена держится ещё пять
 * минут, попробуй через десять-пятнадцать». Клиент вернётся, когда цена уже
 * протухла, и получит «оформи заказ заново» — обещание, которое мы сами же и
 * нарушили. В таком случае честнее сразу отправить в поддержку, там успеют.
 */
const PRICE_LOCK_TIGHT_MINUTES = 20;

/**
 * Текст клиенту. Про баланс, фонд и PaySpace в нём нет ни слова: устройство
 * нашей казны — не его забота, а «недостаточно средств» он прочитал бы как
 * проблему СВОЕЙ карты.
 *
 * Голос — Оплатишки: от первого лица, без канцелярита, без «сбоя на нашей
 * стороне» и без «технических работ» (решения владельца 2026-08-25). Человеку
 * важно не то, что у нас случилось, а что делать дальше и не сгорит ли его
 * цена; «заминка» говорит ровно это и не звучит как поломка, из-за которой
 * стоит забрать деньги и уйти.
 *
 * ⚠️ Обращение на «ВЫ» — тоже решение владельца, и оно расходится с остальным
 * продуктом: чат, бот и кабинет говорят на «ты». Если продукт будут переводить
 * на «вы» целиком, этот текст уже готов; если наоборот — правьте вместе с ним,
 * иначе один экран выпадет из голоса.
 *
 * Срок фиксации называем РЕАЛЬНЫЙ (решение владельца В3): у заказа могло
 * остаться десять минут, и зашитое «цена держится два часа» стало бы обманом.
 */
export function fulfillmentCapacityText(priceLockMinutesLeft: number | null): string {
  const intro = 'Оплата сейчас не проходит — небольшая заминка, уже разбираюсь.';

  if (priceLockMinutesLeft === null) {
    return (
      `${intro} Попробуйте оплатить через ${CAPACITY_RETRY_WINDOW}. ` +
      'Если и тогда не выйдет — напишите в поддержку, там помогут вручную.'
    );
  }

  const lock = `Цена за вами ещё ${formatMinutes(priceLockMinutesLeft)}`;

  if (priceLockMinutesLeft < PRICE_LOCK_TIGHT_MINUTES) {
    return (
      `${intro} ${lock}, поэтому лучше сразу напишите в поддержку — ` +
      'там помогут оформить вручную.'
    );
  }

  return (
    `${intro} ${lock}, так что попробуйте оплатить через ${CAPACITY_RETRY_WINDOW}. ` +
    'Если и тогда не выйдет — напишите в поддержку, там помогут вручную.'
  );
}

/** «43 минуты», «21 минуту», «5 минут» — иначе фраза читается как машинная. */
function formatMinutes(minutes: number): string {
  const lastTwo = minutes % 100;
  const last = minutes % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return `${minutes} минут`;
  if (last === 1) return `${minutes} минуту`;
  if (last >= 2 && last <= 4) return `${minutes} минуты`;
  return `${minutes} минут`;
}
