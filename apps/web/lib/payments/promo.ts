import type { PromoRejectReason } from '@oplati/types';

/**
 * Отказ «промокод сейчас не применить» — маркер и тексты клиенту.
 *
 * Живёт рядом с `bonus.ts` и по той же причине: код нужен продюсеру контракта
 * (`payments/create`) и клиентским каналам, а тянуть ради строки
 * server-only-модуль в компонент кабинета нельзя.
 *
 * ⚠️ Почему 409, а не 422. Тело запроса корректно, и условие клиент выполнил —
 * код работал, когда он его вводил. Это КОНФЛИКТ состояния: пока он думал,
 * активацию забрал другой заказ или вышел срок акции. 409 в проекте уже значит
 * ровно это (`invalid_status`, `order_expired`, `bonus_unavailable`).
 */
export const PROMO_UNAVAILABLE = 'promo_unavailable';

/**
 * Текст на каждую причину отказа.
 *
 * ⚠️ «Нет такого кода» и «код выключен» отвечают ОДИНАКОВО намеренно: разные
 * тексты превратили бы поле ввода в оракул существования кодов, и акцию можно
 * было бы найти перебором до её запуска.
 *
 * Сумму порога в текст не зашиваем — она приходит числом из расчёта, поэтому
 * `order_too_small` говорит про заказ, а не про рубли: единственное место, где
 * порог известен, это строка `promo_codes`, и дублировать её в текст значило бы
 * завести зеркало, которое разъедется при первой же правке акции.
 */
export const PROMO_REJECT_TEXT: Record<PromoRejectReason, string> = {
  not_found: 'Такого промокода нет. Проверь написание.',
  expired: 'Срок действия промокода истёк.',
  already_used: 'Этот промокод ты уже использовал.',
  exhausted: 'Промокод разобрали — активации закончились.',
  order_too_small: 'Промокод не действует на заказ такой суммы.',
  no_headroom: 'К этому заказу промокод не применить — сумма слишком маленькая.',
};

export function promoRejectText(reason: PromoRejectReason): string {
  return PROMO_REJECT_TEXT[reason];
}
