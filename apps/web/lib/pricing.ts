/**
 * Округление рублёвой цены до целого рубля ВВЕРХ.
 *
 * Копеек в ценах не показываем (решение владельца 2026-08-05): «≈ 867,78 ₽»
 * на витрине читается как расчёт бухгалтерии, а не как цена. Направление —
 * вверх: недобор идёт нам в минус, а не клиенту в плюс, и на разнице курса
 * копейка в нашу пользу дешевле, чем копейка в пользу клиента.
 *
 * Применяется ровно в двух точках, и обе обязаны использовать одну функцию:
 * оценка витрины (`lib/catalog/build.ts`) и фиксация суммы заказа
 * (`lib/tool-handlers/propose-order.ts`). Разойдутся — клиент увидит в каталоге
 * одну цену, а в заказе другую.
 *
 * Вход — неотрицательные копейки, УЖЕ приведённые к integer: произведение
 * USD-центов на курс — float, и хвост `32000.000000000004` дал бы лишний рубль
 * на ровной сумме. Выход — integer, кратный 100.
 */
export function roundUpToWholeRubles(kopecks: number): number {
  return Math.ceil(kopecks / 100) * 100;
}

