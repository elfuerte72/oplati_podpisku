/**
 * Переписка (`messages`). Крон `retention`, 04:15.
 *
 * Два года, а не 90 дней (решение владельца 2026-09-09): переписка клиентов с
 * помощником и оператором — обучающий материал для агента поддержки, и квартал
 * его не накапливает (при нынешнем потоке это около пятисот сообщений).
 *
 * ⚠️ Срок конечен намеренно. «Не удалять никогда» означало бы бессрочный архив
 * переписки с телефонами, почтой и жалобами: при утечке базы это весь архив, а
 * не срез за период. Два года — компромисс между обучением и этой ценой.
 */
