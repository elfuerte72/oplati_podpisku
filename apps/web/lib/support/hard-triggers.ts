/**
 * Жёсткие триггеры эскалации (спека §8). Проверяются ДО вызова модели и
 * только в режиме `ai`.
 *
 * Детерминированный список основ слов, а не классификатор: клиент, написавший
 * «верните деньги» или «вы мошенники», должен попасть к человеку независимо
 * от того, что решит модель, — и независимо от того, доступна ли она.
 *
 * Отрицание СРАБАТЫВАЕТ намеренно («оператор не нужен» → к оператору): ложное
 * срабатывание в сторону человека принято владельцем. Обратная ошибка —
 * помощник, уговаривающий клиента не просить возврат, — дороже.
 *
 * ⚠️ «отзыв» — НЕ триггер (двусмысленно: «оставлю отзыв» и «отзыв платежа»).
 * Решение владельца.
 */

export type HardTriggerCategory = 'human' | 'refund' | 'complaint' | 'legal';

export type HardTriggerHit = {
  category: HardTriggerCategory;
  /** Совпавшая основа — идёт оператору как причина передачи. */
  matched: string;
};

/**
 * Основы по категориям, в порядке важности для оператора: просьба о человеке
 * важнее темы, с которой он пришёл.
 *
 * Регэкспы вместо `includes` там, где основа — не подстрока: «верн(и|ите)
 * деньги», «отмен(ите|и) платёж». Границы слов НЕ ставим: русская морфология
 * («оператору», «менеджером», «жалобой») делает основу префиксом слова, и
 * `\b` с кириллицей в JS всё равно не работает.
 */
/**
 * Кириллическая граница слова. `\b` в JS кириллицу не видит, а короткие основы
 * без границы ловят чужие слова: `суд` — «судя по всему», `обман` —
 * «обманчиво», `инн` — «Иннокентий». Граница — «не буква» слева; справа
 * граница НЕ ставится намеренно: русская морфология делает основу префиксом
 * («оператору», «жалобой»).
 */
const B = '(?<![а-яёa-z])';
const w = (stem: string): RegExp => new RegExp(B + stem);

const TRIGGERS: readonly { category: HardTriggerCategory; patterns: readonly RegExp[] }[] = [
  {
    category: 'human',
    patterns: [
      /оператор/,
      /operator/,
      /менеджер/,
      /сотрудник/,
      /живой человек/,
      /живого человека/,
      /с человеком/,
    ],
  },
  {
    category: 'refund',
    patterns: [
      /возврат/,
      /верн(?:и|ите) деньги/,
      /вернуть деньги/,
      /деньги обратно/,
      /refund/,
      /chargeback/,
      /чарджбек/,
      /отмен(?:ите|и) плат[её]ж/,
    ],
  },
  {
    category: 'complaint',
    patterns: [
      w('мошенни'),
      w('обман'),
      w('кинули'),
      w('развод'),
      w('жалоб'),
      // «суд» — целым словом или «судебн-»: «судя по всему» и «посуда» — не претензия.
      /(?<![а-яёa-z])суд(?:[аеуы]|ом|ах)?(?![а-яё])|(?<![а-яёa-z])судебн/,
      w('полици'),
      w('прокуратур'),
      w('роскомнадзор'),
    ],
  },
  {
    category: 'legal',
    patterns: [
      w('реквизит'),
      // «договор» — не «договорились».
      /(?<![а-яёa-z])договор(?:[аеуы]|ом|ах|ов)?(?![а-яё])/,
      // «ИНН» — только целым словом.
      /(?<![а-яёa-z])инн(?![а-яё])/,
      w('огрн'),
      w('юрлиц'),
      /для бухгалтер/,
      /закрывающ/,
      /сч[её]т-фактур/,
      /чек для/,
    ],
  },
];

/**
 * Совпадение с жёстким списком или `null`.
 *
 * Регистронезависимо: текст приводится к нижнему регистру ОДИН раз, а основы
 * записаны строчными. `ё` не схлопывается в `е` глобально — там, где владелец
 * допустил обе формы, они перечислены в самой основе.
 */
export function matchHardTrigger(text: string): HardTriggerHit | null {
  if (!text) return null;
  const haystack = text.toLowerCase();
  for (const { category, patterns } of TRIGGERS) {
    for (const pattern of patterns) {
      const m = pattern.exec(haystack);
      if (m) return { category, matched: m[0] };
    }
  }
  return null;
}
