import { describe, expect, it } from 'vitest';

import { maskForModel, maskForStaff } from './mask';

/**
 * Маскирование перед отправкой стороннему провайдеру (спека §11).
 *
 * Владелец осознанно принял, что переписка уходит на серверы DeepSeek и
 * политика допускает обучение на входах. Именно поэтому номера карт, телефоны
 * и почта не должны уезжать туда в открытом виде: закрыть канал нельзя,
 * значит нужно закрыть содержимое.
 */

describe('maskForModel', () => {
  it('номер карты заменяется маской последних четырёх цифр', () => {
    expect(maskForModel('моя карта 4111 1111 1111 1111 не проходит')).toBe(
      'моя карта **** 1111 не проходит',
    );
  });

  it('карта без пробелов тоже маскируется', () => {
    expect(maskForModel('4111111111111111')).toBe('**** 1111');
  });

  it('почта заменяется плейсхолдером', () => {
    expect(maskForModel('пишите на ivan.petrov+tag@example.com')).toBe(
      'пишите на [email]',
    );
  });

  it('телефон в любом привычном виде заменяется плейсхолдером', () => {
    for (const phone of ['+7 999 123-45-67', '89991234567', '+7(999)123-45-67']) {
      expect(maskForModel(`мой номер ${phone}`)).toBe('мой номер [телефон]');
    }
  });

  it('номер заказа и суммы НЕ маскируются — иначе помощник ослепнет на своём же предмете', () => {
    expect(maskForModel('заказ OP-3417 на 1 190 рублей')).toBe('заказ OP-3417 на 1 190 рублей');
  });

  it('несколько контактов в одном сообщении закрываются все', () => {
    expect(maskForModel('карта 4111111111111111, тел +79991234567, почта a@b.ru')).toBe(
      'карта **** 1111, тел [телефон], почта [email]',
    );
  });

  it('почта с цифрами не превращается в телефон: сначала почта, потом номера', () => {
    expect(maskForModel('логин 79991234567@mail.ru')).toBe('логин [email]');
  });

  it.each([
    'оплатил 2026-08-27 12:30:45',
    'заказ от 2026-08-27',
    'платил 27.08.2026 в 12:30',
  ])('РЕГРЕСС V6: дата и время «%s» — не телефон, остаются как есть', (text) => {
    expect(maskForModel(text)).toBe(text);
  });

  it('РЕГРЕСС V6: телефон рядом с датой маскируется, дата — нет', () => {
    expect(maskForModel('2026-08-27 звонил на +7 999 123-45-67')).toBe('2026-08-27 звонил на [телефон]');
  });

  it('пустая строка и текст без контактов проходят как есть', () => {
    expect(maskForModel('')).toBe('');
    expect(maskForModel('когда придёт карта?')).toBe('когда придёт карта?');
  });
});

describe('maskForStaff', () => {
  it('оператору — только карта под маской; телефон и почта остаются: они нужны для сверки', () => {
    const text = 'Платил с карты 4111 1111 1111 1111, телефон +7 999 123-45-67, почта ivan@example.com';
    const out = maskForStaff(text);
    expect(out).not.toContain('4111 1111 1111 1111');
    expect(out).toContain('+7 999 123-45-67');
    expect(out).toContain('ivan@example.com');
  });

  it('модели — всё под маской, оператору — нет: две маски намеренно разные', () => {
    const text = 'телефон +7 999 123-45-67';
    expect(maskForModel(text)).not.toContain('123-45-67');
    expect(maskForStaff(text)).toContain('123-45-67');
  });
});

