import { redactCardNumbers } from '../telegram/templates';

/**
 * Маскирование текста перед отправкой модели помощника (спека §11).
 *
 * Переписка уходит на серверы стороннего провайдера, и его политика допускает
 * обучение на входах — это принято владельцем осознанно. Раз канал закрыть
 * нельзя, закрываем содержимое: номер карты, телефон и почта модели не нужны
 * ни для одного сценария поддержки, а утечь могут навсегда.
 *
 * ⚠️ Маскируем ТОЛЬКО контакты. Номер заказа, суммы и даты остаются как есть:
 * без них помощник слеп на собственном предмете, а секрета в них нет.
 */

/**
 * Почта. Закрывается ПЕРВОЙ: локальная часть бывает из одних цифр
 * (`79991234567@mail.ru`), и телефонный шаблон, сработавший раньше, разорвал бы
 * адрес пополам — получился бы «[телефон]@mail.ru», то есть и не замаскировано,
 * и нечитаемо.
 */
const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

/**
 * Телефон: 10–15 цифр с необязательным `+` и привычными разделителями.
 *
 * Идёт ПОСЛЕ карт: последовательность из 16 цифр — это карта, и отдать её
 * телефонному шаблону значило бы потерять маску `**** 1111`, по которой
 * оператор потом узнаёт карту в переписке.
 *
 * Границы `(?<!\d)`/`(?!\d)` обязательны: без них шаблон откусывал бы кусок
 * длинного числа и превращал «1234567890123456789» в «[телефон]789».
 */
const PHONE_RE = /(?<![\d+])\+?\d(?:[ .\-()]?\d){9,14}(?!\d)/g;

export function maskForModel(text: string): string {
  if (!text) return text;
  const withoutEmails = text.replace(EMAIL_RE, '[email]');
  // Карты — существующей функцией бота: у неё уже есть проверка Луна, и вторая
  // реализация того же правила была бы зеркалом (инвариант 10).
  const withoutCards = redactCardNumbers(withoutEmails);
  return withoutCards.replace(PHONE_RE, '[телефон]');
}
