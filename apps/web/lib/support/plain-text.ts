/**
 * Ответ модели — в plain text для Telegram.
 *
 * Бот шлёт сообщения без `parse_mode`, а модель, несмотря на промпт, ставит
 * markdown («**оплачен**», «### Что дальше», маркеры списка, обратные кавычки)
 * — клиент видел бы звёздочки и решётки буквально. Разметка снимается, текст
 * остаётся; звёздочка как знак умножения («12 * 3») не трогается.
 *
 * Чистая функция: зовётся в модуле ДО выходного фильтра, доставки и записи —
 * в БД лежит ровно то, что ушло клиенту.
 */
export function toTelegramPlainText(text: string): string {
  return text
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/^[-*]\s+/gm, '— ')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/__(.+?)__/g, '$1')
    .replace(/(^|[^\w*])\*(?!\s)([^*\n]+?)\*(?!\w)/g, '$1$2')
    .replace(/`([^`\n]+)`/g, '$1');
}
