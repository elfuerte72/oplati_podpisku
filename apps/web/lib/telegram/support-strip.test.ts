import { describe, expect, it } from 'vitest';

import { stripHtmlTags } from './support';

/**
 * Обращение оператору собирается как HTML (клиентский бот шлёт с parse_mode),
 * а бот персонала — простым текстом. Снятие разметки поэтому обязано быть
 * ровно таким, чтобы человек прочитал то же самое.
 */
describe('stripHtmlTags', () => {
  it('ссылка на чат остаётся кликабельной, а не превращается в мёртвый текст', () => {
    // Слепое удаление тегов оставляло «Профиль: открыть чат» — то есть кнопку,
    // ради которой строка существует, превращало в ничто.
    const html = 'Профиль: <a href="tg://user?id=379336096">открыть чат</a>';

    expect(stripHtmlTags(html)).toBe('Профиль: открыть чат (tg://user?id=379336096)');
  });

  it('обычная разметка снимается', () => {
    expect(stripHtmlTags('<b>Клиент</b> <i>написал</i>: <code>ORD-J6TBP</code>')).toBe(
      'Клиент написал: ORD-J6TBP',
    );
  });

  it('перенос строки сохраняется', () => {
    expect(stripHtmlTags('первая<br>вторая')).toBe('первая\nвторая');
  });

  it('экранированный текст клиента раскодируется, а не съедается', () => {
    // Порядок важен: раскодируй сущности ДО снятия тегов — и `&lt;b&gt;` из
    // сообщения клиента стал бы разметкой и исчез.
    expect(stripHtmlTags('Клиент писал: &lt;b&gt;жирным&lt;/b&gt; и &amp; ещё')).toBe(
      'Клиент писал: <b>жирным</b> и & ещё',
    );
  });
});
