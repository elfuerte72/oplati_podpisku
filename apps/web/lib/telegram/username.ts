/**
 * @username Telegram — один источник правила на проект.
 *
 * Латиница, цифры и `_`, 4–32 символа (Telegram выдаёт 5–32, но у ранних
 * аккаунтов встречаются четырёхбуквенные). Проверка обязательна, а не «для
 * порядка»: значение приходит из внешнего источника (апдейт бота, ответ
 * `getChat`, колонка в базе) и подставляется в `href`. Символ `/`, `?` или `#`
 * внутри увёл бы ссылку на чужой адрес — из карточки клиента или из
 * уведомления персоналу.
 *
 * ⚠️ Модуль без `server-only` и без зависимостей: им пользуются и панель
 * (`lib/panel/telegram-dm.ts`), и шаблоны бота (`lib/telegram/templates.ts`).
 * Раньше правило жило в обоих местах копией — шестое зеркало проекта, которое
 * разъехалось бы молча (ссылка на чужой профиль в DM персоналу).
 */
const USERNAME_RE = /^[A-Za-z0-9_]{4,32}$/;

/**
 * Приводит username к каноничному виду: снимает ведущую `@` и пробелы.
 * Возвращает `null` для всего, что не похоже на username Telegram.
 */
export function normalizeUsername(raw: string | null | undefined): string | null {
  if (typeof raw !== 'string') return null;
  const trimmed = raw.trim().replace(/^@/, '');
  return USERNAME_RE.test(trimmed) ? trimmed : null;
}
