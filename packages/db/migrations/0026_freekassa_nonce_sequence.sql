-- Монотонный `nonce` для запросов к API Freekassa.
--
-- Провайдер требует: «Уникальный ID запроса, должен всегда быть больше
-- предыдущего значения». Timestamp в миллисекундах не годится — два
-- параллельных запроса в одну миллисекунду дадут одинаковое значение и второй
-- будет отвергнут (а у нас параллельные confirm_order реальны: веб-вкладка +
-- handoff в боте).
--
-- Последовательность монотонна при любой параллельности и переживает
-- перезапуск контейнера. Пропуски (гэпы при откате транзакции) допустимы:
-- требование — «больше предыдущего», а не «без дырок».
--
-- START с запасом от unix-времени в секундах: если раньше по этому магазину
-- уже слались запросы с nonce = time() (SCI-пример из доки провайдера),
-- счётчик с единицы был бы МЕНЬШЕ уже использованного и все запросы получали
-- бы отказ. 2_000_000_000 ≈ 2033-05 — гарантированно выше любого time().
-- Верхняя граница bigint не близка: при 50 заказах в день запас — эры.
CREATE SEQUENCE IF NOT EXISTS "freekassa_nonce" AS bigint START WITH 2000000000 INCREMENT BY 1 NO CYCLE;
