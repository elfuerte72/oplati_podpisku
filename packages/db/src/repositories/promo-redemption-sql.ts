import { sql, type SQL } from 'drizzle-orm';

/**
 * ЕДИНСТВЕННОЕ определение «применение промокода живо»: активация израсходована,
 * а не вернулась клиенту.
 *
 * Модуль отдельный и без импортов намеренно — по образцу
 * `referral-redemption-sql.ts`. Условие нужно и подсчёту активаций («один раз
 * на клиента», «общий лимит кода»), и витринам, и скрипту статистики. Копия
 * означала бы, что клиент получает вторую скидку при исправном на вид учёте, —
 * то есть дыру, видимую только в деньгах.
 *
 * Правило:
 *
 *  - `released` не считается никогда — право вернули (системный откат
 *    несостоявшегося счёта или решение оператора);
 *  - `reserved` под заказом в `expired`/`cancelled` не считается ТОЛЬКО пока по
 *    заказу нет УСПЕШНОГО платежа. Это и есть «денег не приходило»: протухший
 *    черновик или отменённый заказ не должны сжигать промокод.
 *
 * ⚠️ Оговорка про успешный платёж не теоретическая, и она здесь ровно по той же
 * причине, что у баллов. Крон `expire-payments` хоронит заказ и клеймит платёж
 * `pending → failed`, а опоздавший вебхук приходит уже после: путь
 * `paid_after_terminal` (деньги приняты, заказ мёртв) не доходит до
 * `claimPromoSpent`, и строка остаётся `reserved` на `expired`. Без оговорки
 * клиент получал бы и скидку по оплаченному счёту, и промокод обратно.
 *
 * ⚠️ Отличие от баллов: у промокода `failed` НЕ возвращает право автоматически.
 * `failed` — не синоним «деньги вернули» (туда же попадают недоплата и
 * отвергнутый счёт), и автовозврат оттуда раздавал бы вторую скидку по заказам,
 * где деньги у нас. Такой возврат делает человек (`releasePromoRedemption`).
 */
export function livePromoRedemptionSql(
  redemption: SQL | string = sql`promo_redemptions`,
  order: SQL | string = sql`orders`,
) {
  const r = typeof redemption === 'string' ? sql.raw(redemption) : redemption;
  const o = typeof order === 'string' ? sql.raw(order) : order;
  return sql`(
    ${r}.status <> 'released'
    AND NOT (
      ${r}.status = 'reserved'
      AND ${o}.status IN ('expired', 'cancelled')
      AND NOT EXISTS (
        SELECT 1 FROM payments p
        WHERE p.order_id = ${r}.order_id AND p.status = 'succeeded'
      )
    )
  )`;
}
