/**
 * Сроки жизненного цикла виртуальной карты — ЕДИНЫЙ источник правды.
 *
 * Раньше эти числа жили в двух несвязанных местах: литералы
 * `interval '90 days'` / `interval '180 days'` в SQL репозитория карт и
 * константа `CARD_LIFETIME_DAYS` в витрине кабинета. Разъехавшись, они дали бы
 * кабинету обещать клиенту один срок, а cron'у закрывать карту в другой.
 */

/**
 * Через сколько дней БЕЗ наших топапов активная карта помечается `idle`
 * (шаг 1 cron `recycle-cards`).
 *
 * ВАЖНО: «простой» здесь считается по НАШИМ операциям (`updateBalance` при
 * топапе) — списания, которые делает сам сервис подписки, мы не видим
 * (`syncCardBalance` осознанно не трогает `last_used_at`, иначе просмотр
 * кабинета мешал бы recycle). Поэтому `idle` НЕ значит «клиент не пользуется»;
 * это лишь «мы её больше не переиспользуем под новый заказ».
 * `idle` — чистая метка в БД: в провайдер ничего не уходит, карта работает.
 */
export const CARD_IDLE_AFTER_DAYS = 90;

/**
 * Жёсткий срок жизни карты в днях (ТЗ §2: «Карта действует 180 дней»).
 *
 * Отсчёт от `created_at`, НЕ от последнего использования: ровно этот срок
 * кабинет показывает клиенту как «Действует до», и по нему же cron
 * `recycle-cards` делает необратимый `releaseCard` — независимо от того,
 * успела карта стать `idle` или всё ещё `active`.
 */
export const CARD_LIFETIME_DAYS = 180;
