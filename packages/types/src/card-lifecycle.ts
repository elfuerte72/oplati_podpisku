/**
 * Срок жизни виртуальной карты — ЕДИНЫЙ источник правды.
 *
 * Одно число на всё: и витринное «Действует до» в кабинете, и порог, по которому
 * cron `recycle-cards` закрывает карту в провайдере, и окно, внутри которого
 * новый заказ доливает существующую карту вместо выпуска новой. Держать
 * отдельные литералы в SQL и в витрине нельзя — разъехавшись, они дали бы
 * кабинету обещать клиенту один срок, а cron'у закрывать карту в другой.
 *
 * История (решение владельца 2026-07-25): раньше рядом жил второй срок —
 * `active → idle` после 90 дней без НАШИХ топапов. Он остался от отменённой
 * схемы, где закрытая карта уходила в пул и выдавалась ДРУГОМУ клиенту
 * (`findRecyclableCard`); от переиспользования между клиентами отказались —
 * `release` необратим, а один PAN между людьми делить нельзя. Единственным
 * живым эффектом 90 дней осталось то, что на 91-й день клиент терял право на
 * долив и платил `CARD_ISSUE_FEE_USD_CENTS` заново, хотя кабинет обещал ему 180
 * дней. Возрастное идление убрано; статус `idle` сохранён, но ставится он
 * теперь только по делу — когда PaySpace ОТКЛОНИЛ долив (карта протухла,
 * заблокирована, из чужого аккаунта) и `issue-card` выводит её из реюза.
 */

/**
 * Жёсткий срок жизни карты в днях (ТЗ §2: «Карта действует 180 дней»).
 *
 * Отсчёт от `created_at`, НЕ от последнего использования: ровно этот срок
 * кабинет показывает клиенту как «Действует до», внутри него любой новый заказ
 * доливает ту же карту без надбавки за выпуск, а по его истечении cron
 * `recycle-cards` делает необратимый `releaseCard` — независимо от статуса карты.
 */
export const CARD_LIFETIME_DAYS = 180;
