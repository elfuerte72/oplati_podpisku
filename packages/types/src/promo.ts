import { z } from 'zod';

/**
 * Промокоды: нормализация написания и границы ввода (трек promo-codes).
 *
 * Живёт в `@oplati/types`, потому что нормализация нужна ДВУМ сторонам, и они
 * обязаны сойтись символ в символ: скрипт, который заводит код в БД, и проверка
 * кода, введённого клиентом в Mini App. Разъехались бы — заведённый код просто
 * не находился бы, и отладить это можно было бы только глазами по hex-дампу.
 */

/**
 * Латинские буквы, неотличимые на вид от кириллических, → кириллица.
 *
 * Нужно потому, что первый же код кириллический («ДАРЛИНГ»), а клиент набирает
 * его руками с телефона или копирует из поста, где он мог быть набран в
 * смешанной раскладке. «ДAРЛИНГ» с латинской `A` выглядит идентично и на глаз
 * неотличимо ни клиенту, ни нам.
 *
 * ⚠️ Схлопывание разных написаний в один код — НАМЕРЕННОЕ, а не побочный
 * эффект: два кода, различающиеся только раскладкой одной буквы, не должны
 * существовать порознь. UNIQUE-индекс по нормализованному значению это и
 * обеспечивает — второй такой код не заведётся.
 *
 * Направление именно «латиница → кириллица», а не наоборот: коды у нас русские,
 * и обратное отображение схлопывало бы латинские коды в кириллические, которых
 * никто не заводил.
 *
 * ⚠️ Следствие, которое видно не сразу: ЧИСТО ЛАТИНСКИЙ код тоже меняется —
 * «WINTER» становится «WINТЕR» с кириллическими Т и Е. Это не дефект, потому
 * что ту же функцию зовёт скрипт заведения кода: в БД ложится ровно эта строка,
 * и любое написание сходится к ней. Свойство, на котором всё держится, — не
 * «латиница сохраняется», а «одна функция с обеих сторон». Перестанет
 * выполняться второе — заведённый код просто не найдётся, и отладить это можно
 * будет только hex-дампом.
 */
const LATIN_TO_CYRILLIC: ReadonlyMap<string, string> = new Map([
  ['A', 'А'],
  ['B', 'В'],
  ['E', 'Е'],
  ['K', 'К'],
  ['M', 'М'],
  ['H', 'Н'],
  ['O', 'О'],
  ['P', 'Р'],
  ['C', 'С'],
  ['T', 'Т'],
  ['X', 'Х'],
  ['Y', 'У'],
]);

/** Максимальная длина кода — и в БД, и в поле ввода. */
export const PROMO_CODE_MAX_LENGTH = 32;

/**
 * Привести код к каноничному виду: обрезать пробелы, поднять регистр, заменить
 * латинские гомоглифы на кириллицу, выбросить внутренние пробелы и дефисы.
 *
 * Внутренние разделители убираются потому, что «ДАР ЛИНГ» и «ДАР-ЛИНГ» — это
 * попытка ввести тот же код, а не другой; заставлять клиента угадывать
 * пунктуацию незачем.
 *
 * Регистр поднимается ДО замены гомоглифов: таблица знает только заглавные, и
 * обратный порядок пропускал бы строчную латинскую `a`.
 */
export function normalizePromoCode(raw: string): string {
  const upper = raw.trim().toUpperCase();
  let out = '';
  for (const ch of upper) {
    if (ch === ' ' || ch === '-' || ch === '_') continue;
    out += LATIN_TO_CYRILLIC.get(ch) ?? ch;
  }
  return out;
}

/**
 * Схема ввода кода клиентом. Нормализация — частью схемы, чтобы её нельзя было
 * забыть на новом канале: любой разбор тела запроса отдаёт уже канонический код.
 *
 * Длина проверяется ПОСЛЕ нормализации: она выбрасывает пробелы, и вход из
 * одних пробелов обязан упасть как пустой, а не пройти по исходной длине.
 */
export const promoCodeInputSchema = z
  .string()
  .max(PROMO_CODE_MAX_LENGTH * 2)
  .transform(normalizePromoCode)
  .pipe(z.string().min(1).max(PROMO_CODE_MAX_LENGTH));

/**
 * Почему код не применился. Отдельный тип, а не строка в тексте: причина решает
 * и текст клиенту, и то, показывать ли поле ввода дальше.
 */
export const promoRejectReason = z.enum([
  /** Такого кода нет (или он выключен) — одно сообщение на оба случая. */
  'not_found',
  /** Срок действия не начался или уже вышел. */
  'expired',
  /** Клиент уже исчерпал свой лимит применений. */
  'already_used',
  /** Общий лимит активаций кода исчерпан. */
  'exhausted',
  /** Сумма заказа ниже порога, с которого код действует. */
  'order_too_small',
  /**
   * Скидку не на что положить: она не может опустить счёт ниже минимума шлюза,
   * а после усечения от неё не осталось ни рубля.
   */
  'no_headroom',
]);
export type PromoRejectReason = z.infer<typeof promoRejectReason>;
